import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = process.argv[2];
if (sourcePath === undefined) {
  throw new Error("Usage: node scripts/generate-drawingml-presets.mjs <presetShapeDefinitions.xml>");
}

const sourceRevision = "913c78891bd0cd20945b050c63abfb8c66c88009";
const sourceUrl = `https://raw.githubusercontent.com/apache/poi/${sourceRevision}/poi/src/main/resources/org/apache/poi/sl/draw/geom/presetShapeDefinitions.xml`;
const expectedSha256 = "4a762444d8d85876881c02a5b1dedf6f73006fcd8acb7b4e393435615b37c780";
const xml = await readFile(sourcePath, "utf8");
const actualSha256 = createHash("sha256").update(xml).digest("hex");
if (actualSha256 !== expectedSha256) {
  throw new Error(`Unexpected preset definition SHA-256: ${actualSha256}`);
}

const rootBody = xml.match(/<presetShapeDefinitons>([\s\S]*)<\/presetShapeDefinitons>/)?.[1];
if (rootBody === undefined) throw new Error("Invalid preset shape definition root");
const entries = [...rootBody.matchAll(/<([A-Za-z][A-Za-z0-9]*)>([\s\S]*?)<\/\1>/g)]
  .map((match) => ({
    name: match[1],
    xml: match[0].replace(/>\s+</g, "><").trim(),
  }))
  .sort((left, right) => left.name < right.name ? -1 : left.name > right.name ? 1 : 0);
if (entries.length !== 187 || new Set(entries.map(({ name }) => name)).size !== 187) {
  throw new Error(`Expected 187 unique preset definitions, found ${entries.length}`);
}
const generated = `// @generated by scripts/generate-drawingml-presets.mjs; do not edit.
// Source: ${sourceUrl}
// SHA-256: ${expectedSha256}

#[rustfmt::skip]
pub(super) const PRESET_SHAPE_DEFINITIONS: &[(&str, &str)] = &[
${entries.map(({ name, xml: definition }) => `    ("${name}", r###"${definition}"###),`).join("\n")}
];
`;
await writeFile(resolve(root, "core/format/drawingml_presets.rs"), generated);
