import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "third_party/symbol-font-mappings.tsv");
const rustPath = resolve(root, "core/format/symbol_font_mappings.rs");
const typescriptPath = resolve(root, "src/symbol-font-mappings.ts");
const check = process.argv.includes("--check");

const source = await readFile(sourcePath, "utf8");
const sourceSha256 = createHash("sha256").update(source).digest("hex");
const mappings = new Map([
  ["symbol", new Map()],
  ["wingdings", new Map()],
]);

for (const [lineIndex, originalLine] of source.split(/\r?\n/u).entries()) {
  const line = originalLine.trim();
  if (line.length === 0 || line.startsWith("#")) continue;
  const fields = line.split("\t");
  if (fields.length !== 3) throw new Error(`Invalid mapping at line ${lineIndex + 1}`);
  const [family, sourceHex, targetHex] = fields;
  const familyMappings = mappings.get(family);
  if (familyMappings === undefined) throw new Error(`Unknown family ${family} at line ${lineIndex + 1}`);
  if (!/^[0-9A-F]{2}$/u.test(sourceHex) || !/^[0-9A-F]{4,6}$/u.test(targetHex)) {
    throw new Error(`Invalid code point at line ${lineIndex + 1}`);
  }
  const sourceCode = Number.parseInt(sourceHex, 16);
  const targetCode = Number.parseInt(targetHex, 16);
  if (targetCode > 0x10ffff || targetCode >= 0xd800 && targetCode <= 0xdfff) {
    throw new Error(`Invalid Unicode scalar at line ${lineIndex + 1}`);
  }
  if (familyMappings.has(sourceCode)) {
    throw new Error(`Duplicate ${family} source ${sourceHex} at line ${lineIndex + 1}`);
  }
  familyMappings.set(sourceCode, targetCode);
}

const symbol = [...mappings.get("symbol").entries()].sort(([left], [right]) => left - right);
const wingdings = [...mappings.get("wingdings").entries()].sort(([left], [right]) => left - right);
if (symbol.length !== 166 || wingdings.length !== 221) {
  throw new Error(`Expected 166 Symbol and 221 Wingdings mappings, found ${symbol.length} and ${wingdings.length}`);
}
for (const [family, entries, sentinels] of [
  ["symbol", symbol, [[0x41, 0x0391], [0xa3, 0x2264], [0xb7, 0x2022], [0xd3, 0x00a9], [0xe3, 0x00a9]]],
  ["wingdings", wingdings, [[0x21, 0x1f589], [0x3b, 0x1f5b4], [0x71, 0x2751], [0xfc, 0x2713]]],
]) {
  const bySource = new Map(entries);
  for (const [sourceCode, targetCode] of sentinels) {
    if (bySource.get(sourceCode) !== targetCode) {
      throw new Error(`Unexpected ${family} mapping for 0x${sourceCode.toString(16)}`);
    }
  }
}

const rustEntries = (entries) => entries
  .map(([sourceCode, targetCode]) => `    (0x${sourceCode.toString(16).padStart(2, "0")}, 0x${targetCode.toString(16)}),`)
  .join("\n");
const rust = `// @generated by scripts/generate-symbol-font-mappings.mjs; do not edit.
// Source: third_party/symbol-font-mappings.tsv
// SHA-256: ${sourceSha256}

#[rustfmt::skip]
const SYMBOL_MAPPINGS: &[(u8, u32)] = &[
${rustEntries(symbol)}
];

#[rustfmt::skip]
const WINGDINGS_MAPPINGS: &[(u8, u32)] = &[
${rustEntries(wingdings)}
];

pub(super) fn semantic_symbol_font_character(character: char, font_family: &str) -> Option<char> {
    let code_point = character as u32;
    let source = if code_point <= 0xff {
        code_point as u8
    } else if (0xf000..=0xf0ff).contains(&code_point) {
        (code_point & 0xff) as u8
    } else {
        return None;
    };
    let normalized_family = font_family.trim().trim_matches(['\\'', '\"']);
    let mappings = if normalized_family.eq_ignore_ascii_case("Symbol") {
        SYMBOL_MAPPINGS
    } else if normalized_family.eq_ignore_ascii_case("Wingdings") {
        WINGDINGS_MAPPINGS
    } else {
        return None;
    };
    let index = mappings
        .binary_search_by_key(&source, |(source, _)| *source)
        .ok()?;
    char::from_u32(mappings[index].1)
}
`;

const typescriptEntries = (entries) => entries
  .map(([sourceCode, targetCode]) => `  [0x${sourceCode.toString(16).padStart(2, "0")}, 0x${targetCode.toString(16)}],`)
  .join("\n");
const typescript = `// @generated by scripts/generate-symbol-font-mappings.mjs; do not edit.
// Source: third_party/symbol-font-mappings.tsv
// SHA-256: ${sourceSha256}

const SYMBOL_MAPPINGS: readonly (readonly [number, number])[] = Object.freeze([
${typescriptEntries(symbol)}
]);
const WINGDINGS_MAPPINGS: readonly (readonly [number, number])[] = Object.freeze([
${typescriptEntries(wingdings)}
]);

function lookup(entries: readonly (readonly [number, number])[], source: number): number | undefined {
  let low = 0;
  let high = entries.length - 1;
  while (low <= high) {
    const middle = (low + high) >>> 1;
    const [candidate, target] = entries[middle]!;
    if (candidate === source) return target;
    if (candidate < source) low = middle + 1;
    else high = middle - 1;
  }
  return undefined;
}

/** Returns readable Unicode while leaving exact legacy-font glyph runs untouched. */
export function semanticSymbolFontText(text: string, fontFamily: string): string {
  const family = fontFamily.trim().replace(/^(['\"])(.*)\\1$/u, "$2").toLowerCase();
  const mappings = family === "symbol"
    ? SYMBOL_MAPPINGS
    : family === "wingdings"
      ? WINGDINGS_MAPPINGS
      : undefined;
  if (mappings === undefined) return text;
  let normalized = "";
  for (const character of text) {
    const codePoint = character.codePointAt(0)!;
    const source = codePoint <= 0xff
      ? codePoint
      : codePoint >= 0xf000 && codePoint <= 0xf0ff
        ? codePoint & 0xff
        : undefined;
    const target = source === undefined ? undefined : lookup(mappings, source);
    normalized += target === undefined ? character : String.fromCodePoint(target);
  }
  return normalized;
}
`;

for (const [path, generated] of [[rustPath, rust], [typescriptPath, typescript]]) {
  if (!check) {
    await writeFile(path, generated);
    continue;
  }
  const current = await readFile(path, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(`${path} is stale; run node scripts/generate-symbol-font-mappings.mjs`);
  }
}
